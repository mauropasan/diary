#!/usr/bin/env bash

# Build a signed release APK and publish it where the Laravel `/download`
# route serves it (storage/app/apk/diary.apk), so the install link always
# points to the latest build.
#
# Requirements:
#   - Node.js >= 22 (Capacitor CLI)
#   - JDK 17+
#   - Android SDK (ANDROID_HOME / ANDROID_SDK_ROOT, or android/local.properties)
#   - A .env with DIARY_KEYSTORE_PASSWORD and DIARY_KEY_ALIAS (and optionally
#     DIARY_KEY_PASSWORD, defaulting to the store password)
#   - The release keystore at storage/app/diary-release.keystore

set -euo pipefail

cd "$(dirname "$0")/.."

KEYSTORE="$PWD/storage/app/diary-release.keystore"
PROPERTIES="android/diary-build.properties"
OUTPUT_APK="android/app/build/outputs/apk/release/app-release.apk"
PUBLISHED_APK="storage/app/apk/diary.apk"

env_value() {
    sed -n "s/^${1}=//p" .env 2>/dev/null | head -1 | tr -d '\r' | tr -d '"'"'"''
}

# The signing config is appended to the generated build.gradle, which
# `npx cap add android` recreates from the Capacitor template; re-add the
# platform when it is missing, and the block when it was regenerated.
if [ ! -d android ]; then
    npx cap add android
fi

# The whole `android/` tree is gitignored (it is regenerated from the Capacitor
# template), so the native pieces the app needs are re-created here whenever
# they are missing. Each block is a no-op once the file or marker exists, which
# keeps the script safe to re-run after `npx cap add android` wipes the project.
PLUGIN_DIR="android/app/src/main/java/es/diario/app"
PLUGIN_FILE="$PLUGIN_DIR/DiarySecurityPlugin.java"

if [ ! -f "$PLUGIN_FILE" ]; then
    mkdir -p "$PLUGIN_DIR"
    cat > "$PLUGIN_FILE" <<'JAVA'
package es.diario.app;

import android.content.Context;
import android.os.Build;
import android.security.keystore.KeyGenParameterSpec;
import android.security.keystore.KeyProperties;
import android.util.Base64;

import androidx.annotation.NonNull;
import androidx.biometric.BiometricManager;
import androidx.biometric.BiometricPrompt;

import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;

import java.security.KeyStore;
import java.util.concurrent.Executor;

import javax.crypto.Cipher;
import javax.crypto.KeyGenerator;
import javax.crypto.SecretKey;
import javax.crypto.spec.GCMParameterSpec;

/**
 * Bridges the Android Keystore and the biometric prompt to the web layer.
 *
 * The web app never sees raw key material: it hands over base64 plaintext and
 * gets base64 ciphertext back, so a compromised WebView cannot exfiltrate the key.
 */
@CapacitorPlugin(name = "DiarySecurity")
public class DiarySecurityPlugin extends Plugin {

    private static final String ANDROID_KEYSTORE = "AndroidKeyStore";
    private static final String KEY_PREFIX = "diary.security.";
    private static final String TRANSFORMATION = "AES/GCM/NoPadding";
    private static final int IV_LENGTH = 12;
    private static final int TAG_LENGTH_BITS = 128;

    /** Aliases become part of a Keystore entry name, so keep them to a predictable charset. */
    private static final String ALIAS_PATTERN = "[A-Za-z0-9._-]+";

    /** Held only for the duration of an in-flight prompt so we can reject once and only once. */
    private PluginCall pendingBiometricCall;

    @PluginMethod
    public void encrypt(PluginCall call) {
        String alias = call.getString("alias");
        String data = call.getString("data");

        if (!isValidAlias(alias)) {
            call.reject("Missing or invalid alias", "BAD_INPUT");
            return;
        }
        if (data == null) {
            call.reject("Missing data", "BAD_INPUT");
            return;
        }

        byte[] plaintext;
        try {
            plaintext = Base64.decode(data, Base64.DEFAULT);
        } catch (IllegalArgumentException ex) {
            call.reject("data is not valid base64", "BAD_INPUT", ex);
            return;
        }

        try {
            Cipher cipher = Cipher.getInstance(TRANSFORMATION);
            cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey(alias));

            // IV is generated by the provider and must travel with the ciphertext.
            byte[] iv = cipher.getIV();
            byte[] ciphertext = cipher.doFinal(plaintext);

            byte[] packed = new byte[iv.length + ciphertext.length];
            System.arraycopy(iv, 0, packed, 0, iv.length);
            System.arraycopy(ciphertext, 0, packed, iv.length, ciphertext.length);

            JSObject result = new JSObject();
            result.put("data", Base64.encodeToString(packed, Base64.NO_WRAP));
            call.resolve(result);
        } catch (Exception ex) {
            call.reject("Encryption failed", "ENCRYPT_FAILED", ex);
        }
    }

    @PluginMethod
    public void decrypt(PluginCall call) {
        String alias = call.getString("alias");
        String data = call.getString("data");

        if (!isValidAlias(alias)) {
            call.reject("Missing or invalid alias", "BAD_INPUT");
            return;
        }
        if (data == null) {
            call.reject("Missing data", "BAD_INPUT");
            return;
        }

        byte[] packed;
        try {
            packed = Base64.decode(data, Base64.DEFAULT);
        } catch (IllegalArgumentException ex) {
            call.reject("data is not valid base64", "BAD_INPUT", ex);
            return;
        }
        if (packed.length <= IV_LENGTH) {
            call.reject("data is too short to contain an IV", "BAD_INPUT");
            return;
        }

        try {
            KeyStore keyStore = KeyStore.getInstance(ANDROID_KEYSTORE);
            keyStore.load(null);
            if (!keyStore.containsAlias(keyName(alias))) {
                call.reject("No key for this alias", "KEY_MISSING");
                return;
            }
        } catch (Exception ex) {
            call.reject("Could not read the keystore", "KEY_MISSING", ex);
            return;
        }

        try {
            byte[] iv = new byte[IV_LENGTH];
            byte[] ciphertext = new byte[packed.length - IV_LENGTH];
            System.arraycopy(packed, 0, iv, 0, IV_LENGTH);
            System.arraycopy(packed, IV_LENGTH, ciphertext, 0, ciphertext.length);

            Cipher cipher = Cipher.getInstance(TRANSFORMATION);
            cipher.init(Cipher.DECRYPT_MODE, getExistingKey(alias), new GCMParameterSpec(TAG_LENGTH_BITS, iv));
            byte[] plaintext = cipher.doFinal(ciphertext);

            JSObject result = new JSObject();
            result.put("data", Base64.encodeToString(plaintext, Base64.NO_WRAP));
            call.resolve(result);
        } catch (Exception ex) {
            // GCM failures are indistinguishable by design; surface one coded error.
            call.reject("Decryption failed", "DECRYPT_FAILED", ex);
        }
    }

    @PluginMethod
    public void biometricAvailable(PluginCall call) {
        Context context = getContext();
        BiometricManager manager = BiometricManager.from(context);

        // DEVICE_CREDENTIAL keeps the feature usable on devices without a fingerprint sensor.
        int authenticators = BiometricManager.Authenticators.BIOMETRIC_STRONG | BiometricManager.Authenticators.DEVICE_CREDENTIAL;
        int canAuthenticate = Build.VERSION.SDK_INT >= Build.VERSION_CODES.R
            ? manager.canAuthenticate(authenticators)
            : manager.canAuthenticate(BiometricManager.Authenticators.BIOMETRIC_STRONG);

        JSObject result = new JSObject();
        result.put("available", canAuthenticate == BiometricManager.BIOMETRIC_SUCCESS);
        result.put("enrolled", canAuthenticate != BiometricManager.BIOMETRIC_ERROR_NONE_ENROLLED);
        result.put("reason", canAuthenticate);
        call.resolve(result);
    }

    @PluginMethod
    public void biometricVerify(PluginCall call) {
        String title = call.getString("title");
        if (title == null || title.isEmpty()) {
            call.reject("Missing title", "BAD_INPUT");
            return;
        }
        String subtitle = call.getString("subtitle");
        String description = call.getString("description");

        if (pendingBiometricCall != null) {
            call.reject("A biometric prompt is already showing", "BIOMETRIC_ERROR_BUSY");
            return;
        }

        if (!(getActivity() instanceof androidx.fragment.app.FragmentActivity)) {
            call.reject("No activity available for biometric prompt", "BIOMETRIC_ERROR_NO_ACTIVITY");
            return;
        }

        androidx.fragment.app.FragmentActivity activity = (androidx.fragment.app.FragmentActivity) getActivity();
        if (activity.isFinishing() || (Build.VERSION.SDK_INT >= Build.VERSION_CODES.JELLY_BEAN_MR1 && activity.isDestroyed())) {
            call.reject("Activity is finishing", "BIOMETRIC_ERROR_NO_ACTIVITY");
            return;
        }

        if (getBridge() != null) {
            // Keeps the call alive across the (potentially long) prompt; the deprecated
            // Plugin#saveCall variant is replaced by the bridge-level call.
            getBridge().saveCall(call);
        }
        pendingBiometricCall = call;

        activity.runOnUiThread(new Runnable() {
            @Override
            public void run() {
                Executor executor = new android.os.Handler(android.os.Looper.getMainLooper())::post;

                BiometricPrompt.PromptInfo.Builder info = new BiometricPrompt.PromptInfo.Builder()
                    .setTitle(title)
                    .setConfirmationRequired(false);
                if (subtitle != null) {
                    info.setSubtitle(subtitle);
                }
                if (description != null) {
                    info.setDescription(description);
                }

                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
                    // Allowing the device credential removes the negative button, which avoids
                    // the per-OEM rendering bugs around a custom "Cancel" action.
                    info.setAllowedAuthenticators(
                        BiometricManager.Authenticators.BIOMETRIC_STRONG | BiometricManager.Authenticators.DEVICE_CREDENTIAL
                    );
                } else {
                    info.setAllowedAuthenticators(BiometricManager.Authenticators.BIOMETRIC_STRONG);
                    info.setNegativeButtonText(call.getString("cancelTitle", "Cancel"));
                }

                BiometricPrompt prompt = new BiometricPrompt(
                    (androidx.fragment.app.FragmentActivity) getActivity(),
                    executor,
                    new BiometricPrompt.AuthenticationCallback() {
                        @Override
                        public void onAuthenticationSucceeded(@NonNull BiometricPrompt.AuthenticationResult result) {
                            finishBiometric("OK", null, null);
                        }

                        @Override
                        public void onAuthenticationError(int errorCode, @NonNull CharSequence errString) {
                            // The negative button (and a user-initiated dismissal) is a cancellation,
                            // not a hard failure, so the web layer can distinguish the two.
                            if (errorCode == BiometricPrompt.ERROR_NEGATIVE_BUTTON
                                || errorCode == BiometricPrompt.ERROR_USER_CANCELED) {
                                finishBiometric("FAILED", "BIOMETRIC_CANCELLED", errString.toString());
                                return;
                            }
                            finishBiometric("FAILED", "BIOMETRIC_ERROR_" + errorCode, errString.toString());
                        }

                        // onAuthenticationFailed is a single bad scan, not a terminal state: keep the prompt open.
                        @Override
                        public void onAuthenticationFailed() {}
                    }
                );

                prompt.authenticate(info.build());
            }
        });
    }

    /**
     * Resolves or rejects the in-flight biometric call exactly once. The tag is
     * "OK" for success and anything else for a coded rejection.
     */
    private void finishBiometric(String tag, String code, String message) {
        PluginCall call = pendingBiometricCall;
        if (call == null) {
            return;
        }
        // Clear first so a late framework callback cannot resolve twice.
        pendingBiometricCall = null;

        if ("OK".equals(tag)) {
            JSObject result = new JSObject();
            result.put("success", true);
            call.resolve(result);
            return;
        }

        String resolvedCode = code == null ? "BIOMETRIC_CANCELLED" : code;
        String resolvedMessage = message == null ? "Biometric authentication failed" : message;
        call.reject(resolvedMessage, resolvedCode);
    }

    private boolean isValidAlias(String alias) {
        return alias != null && !alias.isEmpty() && alias.matches(ALIAS_PATTERN);
    }

    private String keyName(String alias) {
        return KEY_PREFIX + alias;
    }

    /**
     * Creates the key on first use; no user authentication is bound to it, since the
     * biometric prompt is a separate, optional gate driven by the web layer.
     */
    private SecretKey getOrCreateKey(String alias) throws Exception {
        KeyStore keyStore = KeyStore.getInstance(ANDROID_KEYSTORE);
        keyStore.load(null);

        String name = keyName(alias);
        if (keyStore.containsAlias(name)) {
            return (SecretKey) keyStore.getKey(name, null);
        }

        KeyGenerator generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE);
        generator.init(
            new KeyGenParameterSpec.Builder(name, KeyProperties.PURPOSE_ENCRYPT | KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setRandomizedEncryptionRequired(true)
                .build()
        );
        return generator.generateKey();
    }

    private SecretKey getExistingKey(String alias) throws Exception {
        KeyStore keyStore = KeyStore.getInstance(ANDROID_KEYSTORE);
        keyStore.load(null);
        return (SecretKey) keyStore.getKey(keyName(alias), null);
    }
}
JAVA
fi

MAIN_ACTIVITY="$PLUGIN_DIR/MainActivity.java"

cat > "$MAIN_ACTIVITY" <<'JAVA'
package es.diario.app;

import android.os.Bundle;

import com.getcapacitor.BridgeActivity;

public class MainActivity extends BridgeActivity {

    @Override
    public void onCreate(Bundle savedInstanceState) {
        // Registered before super.onCreate so the bridge sees it during plugin loading.
        registerPlugin(DiarySecurityPlugin.class);
        super.onCreate(savedInstanceState);
    }
}
JAVA

KEYSTORE_PASSWORD="$(env_value DIARY_KEYSTORE_PASSWORD)"
KEY_ALIAS="$(env_value DIARY_KEY_ALIAS)"
KEY_PASSWORD="$(env_value DIARY_KEY_PASSWORD)"

if [ -z "$KEYSTORE_PASSWORD" ] || [ -z "$KEY_ALIAS" ]; then
    echo "DIARY_KEYSTORE_PASSWORD and DIARY_KEY_ALIAS must be set in .env" >&2
    exit 1
fi

if [ ! -f "$KEYSTORE" ]; then
    echo "Keystore not found: $KEYSTORE" >&2
    echo "Back it up: losing it makes future updates uninstallable." >&2
    exit 1
fi

# The commit count only ever grows, so every build has a higher versionCode
# than the previous one and Android accepts it as an update.
VERSION_CODE="$(git rev-list --count HEAD)"

cat > "$PROPERTIES" <<EOF
storeFile=$KEYSTORE
storePassword=$KEYSTORE_PASSWORD
keyAlias=$KEY_ALIAS
keyPassword=${KEY_PASSWORD:-$KEYSTORE_PASSWORD}
versionCode=$VERSION_CODE
versionName=1.$VERSION_CODE
EOF

if ! grep -q 'BEGIN DIARY SIGNING' android/app/build.gradle; then
    cat >> android/app/build.gradle <<'EOF'

// BEGIN DIARY SIGNING
// Appended by scripts/apk.sh; removed when `npx cap add android` regenerates
// the project, so the script re-adds it on the next build. Do not edit.
android {
    def diaryBuild = new Properties()
    diaryBuild.load(new FileInputStream(rootProject.file('diary-build.properties')))

    signingConfigs {
        release {
            storeFile file(diaryBuild.getProperty('storeFile'))
            storePassword diaryBuild.getProperty('storePassword')
            keyAlias diaryBuild.getProperty('keyAlias')
            keyPassword diaryBuild.getProperty('keyPassword')
        }
    }
    defaultConfig {
        versionCode diaryBuild.getProperty('versionCode') as int
        versionName diaryBuild.getProperty('versionName')
    }
    buildTypes {
        release {
            signingConfig signingConfigs.release
        }
    }
}
// END DIARY SIGNING
EOF
fi

if ! grep -q 'androidx.biometric:biometric' android/app/build.gradle; then
    perl -0pi -e 's{(dependencies \{\n)}{$1    // Backports BiometricPrompt and BiometricManager to every API we support.\n    implementation "androidx.biometric:biometric:\$androidxBiometricVersion"\n}' android/app/build.gradle
fi

if ! grep -q 'androidxBiometricVersion' android/variables.gradle; then
    perl -0pi -e "s{(ext \{\n)}{\$1    androidxBiometricVersion = '1.1.0'\n}" android/variables.gradle
fi

if ! grep -q 'USE_BIOMETRIC' android/app/src/main/AndroidManifest.xml; then
    perl -0pi -e 's{(\s*)(<uses-permission android:name="android.permission.INTERNET" />\n)}{$1$2$1<uses-permission android:name="android.permission.USE_BIOMETRIC" />\n}' android/app/src/main/AndroidManifest.xml
fi

# The keyboard must resize the WebView instead of panning the window: without
# this, focusing a field slides the whole page (title bar included) off-screen.
if ! grep -q 'windowSoftInputMode' android/app/src/main/AndroidManifest.xml; then
    perl -0pi -e 's{(android:configChanges="[^\n]+"\n)}{$1            android:windowSoftInputMode="adjustResize"\n}' android/app/src/main/AndroidManifest.xml
fi

npx cap sync android

(cd android && ./gradlew assembleRelease)

mkdir -p "$(dirname "$PUBLISHED_APK")"
cp "$OUTPUT_APK" "$PUBLISHED_APK"

APP_URL="$(env_value APP_URL)"
VERSION="$(sed -n 's/^versionName=//p' "$PROPERTIES")"

# The installed shell reads this from /download/version to know whether it is
# behind the published build, so it goes out with the APK on every release.
PUBLISHED_VERSION="$(dirname "$PUBLISHED_APK")/version.json"
cat > "$PUBLISHED_VERSION" <<EOF
{"versionCode": $VERSION_CODE, "versionName": "$VERSION", "publishedAt": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"}
EOF

echo "APK published: $PUBLISHED_APK (version $VERSION)"
echo "Install link:  ${APP_URL:-<APP_URL>}/download"
